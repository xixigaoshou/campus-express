# ---------- 工具函数 ----------
def style_para(p, indent=True, align=None):
    pf = p.paragraph_format
    if indent:
        pf.first_line_indent = Pt(24)  # 小四两字符
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.0
    if align:
        pf.alignment = align

def set_font(run, size=12, bold=False, cn="宋体", en="Times New Roman"):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = en
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = rPr.makeelement(qn("w:rFonts"), {})
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:ascii"), en)
    rFonts.set(qn("w:hAnsi"), en)
    rFonts.set(qn("w:eastAsia"), cn)

def add_h1(text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.0
    pf.space_before = Pt(2)
    pf.space_after = Pt(1)
    run = p.add_run(text)
    set_font(run, size=16, bold=True)  # 宋体三号加粗
    return p

def add_h2(text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.0
    pf.space_before = Pt(1)
    pf.space_after = Pt(0)
    run = p.add_run(text)
    set_font(run, size=16, bold=True)
    return p

def add_para(text):
    p = doc.add_paragraph()
    style_para(p)
    run = p.add_run(text)
    set_font(run)
    return p

def add_table(headers, rows, widths=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    # 手动添加表格边框（模板无 Table Grid 样式）
    tbl = t._tbl
    tblPr = tbl.tblPr
    borders = tblPr.makeelement(qn("w:tblBorders"), {})
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = tblPr.makeelement(qn("w:" + edge), {})
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        borders.append(el)
    tblPr.append(borders)
    for j, h in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        set_font(run, size=10.5, bold=True)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            cell.text = ""
            p = cell.paragraphs[0]
            run = p.add_run(str(val))
            set_font(run, size=10.5, bold=False)
    if widths:
        for j, w in enumerate(widths):
            for i in range(len(t.rows)):
                t.rows[i].cells[j].width = Cm(w)
    return t

