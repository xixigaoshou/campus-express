add_h2("6.2 接单与抢单规则")
add_para("规则R-6：只有状态为“待接单”的订单可以被接单。规则R-7：同一订单在同一时刻只能被一个接单者成功承接，通过订单表的乐观锁版本号机制保证并发安全，更新影响行数为零即判定抢单失败。规则R-8：接单者不能承接自己发布的订单。规则R-9：接单者信誉等级对应不同的同时进行中订单数量上限，超过上限时禁止继续接单。规则R-10：接单者可浏览全部待接单需求，但不得通过任何手段恶意囤积订单、干扰他人接单。")

add_h2("6.3 订单取消规则")
add_para("规则R-11：需求方在订单处于“待接单”状态时可无条件取消；订单被接单后原则上不能取消，确有需要需与接单者协商一致。规则R-12：接单者在“已接单、取件中”状态下因客观原因无法履约时，可申请取消订单，系统将订单重新置为“待接单”并通知需求方，同时进行信誉扣分。规则R-13：订单取消后已产生的留言记录予以保留，便于双方沟通追溯；涉及报酬的取消场景不产生报酬结算。")

add_h2("6.4 超时处理规则")
add_para("规则R-14：订单发布后超过设定时限（如24小时）仍无人接单的，系统自动提醒发布者，可延长接单期限或调整报酬金额。规则R-15：接单者承接后超过设定时限（如2小时）未更新为“取件中”的，系统发送提醒；超过更长期限仍未履约的，自动取消订单并重新开放，同时进行信誉扣分。规则R-16：接单者标记送达后，需求方超过设定时限（如24小时）未确认收货的，系统默认自动确认收货，将订单置为“已完成”，保障接单者权益。")

add_h2("6.5 报酬结算规则")
add_para("规则R-17：报酬金额由需求方发布需求时设定，系统校验金额在允许范围内（如0.5元至50元）。规则R-18：订单完成后，系统记录实际报酬金额作为接单者收入依据，个人订单中心展示累计收入。规则R-19：订单取消场景下，除双方协商一致情形外不产生报酬结算；已完成订单的报酬结算记录不允许修改或删除。规则R-20：平台现阶段以信息撮合为主，不代收代付报酬，具体结算由订单双方线下完成，订单完成页提供结算引导说明。")

add_h2("6.6 评价与信誉规则")
add_para("规则R-21：只有状态为“已完成”的订单允许评价，评价时限为订单完成后7天内。规则R-22：双方完成互评后系统更新信誉分值：4星及以上每单信誉分加1分，3星及以下每单扣2分；被认定恶意取消订单每次扣5分。规则R-23：信誉分值低于设定阈值（如80分）时用户禁止接单，恢复至阈值以上后解除限制。规则R-24：信誉等级按分值区间划分：普通（80-99）、良好（100-119）、优秀（120以上），在个人主页与接单者详情中展示。规则R-25：用户不得通过虚假订单刷取信誉分，一经发现扣除双倍信誉分并视情节禁用账户。")
